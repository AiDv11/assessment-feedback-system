    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
    if (currentStudentId == null || currentStudentId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Student session not found.");
        return;
    }

    if (cboClass.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this, "Please select a class.");
        return;
    }

    String comment = txtComment.getText().trim();

    if (comment.isEmpty() || isPlaceholderActive) {
        JOptionPane.showMessageDialog(this, "Please enter a comment.");
        return;
    }

    if (comment.length() > 200) {
        JOptionPane.showMessageDialog(this, "Comment too long (max 200 characters).");
        return;
    }
 

    String classId = cboClass.getSelectedItem().toString().split(" - ")[0];
    String lecturerId = lblLecturer.getText().trim();

    try {

        appendLineSafe(COMMENTS_FILE,
                currentStudentId + "|" + lecturerId + "|" + classId + "|" + comment.replace("\n", " "));

        JOptionPane.showMessageDialog(this, "Comment submitted!");
        txtComment.setText("");

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Failed to submit: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnSubmitActionPerformed


