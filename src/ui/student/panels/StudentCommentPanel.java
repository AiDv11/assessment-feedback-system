    private final String COMMENT_PLACEHOLDER = "Type your comment here...";
    private boolean isPlaceholderActive = true;
    private void setupPlaceholder() {
    txtComment.setText(COMMENT_PLACEHOLDER);
    txtComment.setForeground(java.awt.Color.GRAY);
    isPlaceholderActive = true;

    txtComment.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusGained(java.awt.event.FocusEvent e) {
            if (isPlaceholderActive) {
                txtComment.setText("");
                txtComment.setForeground(java.awt.Color.BLACK);
                isPlaceholderActive = false;
            }
        }

        @Override
        public void focusLost(java.awt.event.FocusEvent e) {
            if (txtComment.getText().trim().isEmpty()) {
                txtComment.setText(COMMENT_PLACEHOLDER);
                txtComment.setForeground(java.awt.Color.GRAY);
                isPlaceholderActive = true;
            }
        }
    });
}


    
private static final String COMMENTS_FILE = "data/comments.txt";
private static final String ENROLL_FILE   = "data/enrollments.txt";
private static final String CLASSES_FILE  = "data/classes.txt";

private String currentStudentId;


public void refreshComments(String studentId) {
    this.currentStudentId = studentId;

   
    txtComment.setText(COMMENT_PLACEHOLDER);
    txtComment.setForeground(java.awt.Color.GRAY);
    isPlaceholderActive = true;

    javax.swing.SwingUtilities.invokeLater(() -> {
        txtComment.setCaretPosition(0);
        jScrollPane1.getViewport().setViewPosition(new java.awt.Point(0, 0));
    });

    loadEnrolledClasses();
}



private List<String> readLinesSafe(String filePath) {
        return FileManager.readFile(filePath);
    }

private void appendLineSafe(String filePath, String line) throws Exception {
        if (!FileManager.appendToFile(filePath, line)) {
            throw new Exception("Failed to append to file: " + filePath);
        }
    }

private void loadEnrolledClasses() {
    cboClass.removeAllItems();

    List<String> classLines = readLinesSafe(CLASSES_FILE);

    for (String c : classLines) {
        String[] cp = c.split("\\|");


        if (cp.length >= 3) {
            String classId = cp[0];
            String className = cp[2];

            String display = classId + " - " + className;
            cboClass.addItem(display);
        }
    }

    if (cboClass.getItemCount() > 0) {
        cboClass.setSelectedIndex(0);
        updateLecturerLabelFromSelectedClass();
    } else {
        lblLecturer.setText("-");
        JOptionPane.showMessageDialog(this, "No classes found.");
    }
}

private void updateLecturerLabelFromSelectedClass() {
    if (cboClass.getSelectedItem() == null) {
        lblLecturer.setText("-");
        return;
    }

    String classId = cboClass.getSelectedItem().toString().split(" - ")[0];
    List<String> classLines = readLinesSafe(CLASSES_FILE);

    for (String c : classLines) {
        String[] cp = c.split("\\|");
        if (cp.length >= 4 && cp[0].equals(classId)) {
            lblLecturer.setText(cp[5]); // lecturerId
            return;
        }
    }
    lblLecturer.setText("-");
}






