    private void loadProfileFromFile() {
        List<String> lines = readLinesSafe(USERS_FILE);

        for (String line : lines) {
            String[] p = line.split("\\|");

                if (p.length >= 9 && p[0].trim().equalsIgnoreCase(currentStudentId.trim())) {

                String fullName = p[3];
                String firstName = "";
                String lastName = "";

                if (fullName.contains(" ")) {
                    int idx = fullName.lastIndexOf(" ");
                    firstName = fullName.substring(0, idx);
                    lastName = fullName.substring(idx + 1);
                    
                } else {
                    firstName = fullName;
                }

                txtFirstName.setText(firstName);
                txtLastName.setText(lastName);

                txtEmail.setText(p[5]);
                txtPhone.setText(p[6]);

                txtPassword.setText("");
                txtConfirmPassword.setText("");

                return;
            }
        }

        JOptionPane.showMessageDialog(this, "Student record not found.");
    }


