    private List<String> readLinesSafe(String filePath) {
        return FileManager.readFile(filePath);
    }

    private void writeLinesSafe(String filePath, List<String> lines) throws Exception {
        if (!FileManager.writeFile(filePath, lines)) {
            throw new Exception("Failed to write file: " + filePath);
        }
    }



