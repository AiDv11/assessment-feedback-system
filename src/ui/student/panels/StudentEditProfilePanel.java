    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        String firstName = txtFirstName.getText().equals(EX_FIRST_NAME) ? "" : txtFirstName.getText().trim();
        String lastName  = txtLastName.getText().equals(EX_LAST_NAME)  ? "" : txtLastName.getText().trim();
        String phone     = txtPhone.getText().equals(EX_PHONE)         ? "" : txtPhone.getText().trim();
        String email     = txtEmail.getText().equals(EX_EMAIL)         ? "" : txtEmail.getText().trim();


        String password = new String(txtPassword.getPassword()).trim();
        String confirmPassword = new String(txtConfirmPassword.getPassword()).trim();

        if (firstName.isEmpty() || lastName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "First name and last name cannot be empty.");
            return;
        }

        if (phone.isEmpty() || !phone.matches("\\d{8,15}")) {
            JOptionPane.showMessageDialog(this, "Phone number must contain only digits (8–15 digits).");
            return;
        }

        if (email.isEmpty() || !email.contains("@") || !email.contains(".")) {
            JOptionPane.showMessageDialog(this, "Invalid email format.");
            return;
        }


        String fullName = firstName + " " + lastName;


        boolean wantsPasswordChange = !password.isEmpty() || !confirmPassword.isEmpty();
        if (wantsPasswordChange) {
            if (password.length() < 6) {
                JOptionPane.showMessageDialog(this, "Password must be at least 6 characters.");
                return;
            }
            if (!password.equals(confirmPassword)) {
                JOptionPane.showMessageDialog(this, "Passwords do not match.");
                return;
            }
        }


        List<String> lines = readLinesSafe(USERS_FILE);
        boolean updated = false;

        for (int i = 0; i < lines.size(); i++) {
            String[] p = lines.get(i).split("\\|");

                if (p.length >= 9 && p[0].trim().equalsIgnoreCase(currentStudentId.trim())) {
                String username = p[1];
                String oldPassword = p[2];
                String gender = p[4];
                String age = p[7];
                String role = p[8];

                String finalPassword = wantsPasswordChange ? password : oldPassword;

                String newLine = currentStudentId + "|" + username + "|" + finalPassword + "|"
                        + fullName + "|" + gender + "|" + email + "|" + phone + "|" + age + "|" + role;

                lines.set(i, newLine);
                updated = true;
                break;
            }
        }

        if (!updated) {
            JOptionPane.showMessageDialog(this, "Student record not found to update.");
            return;
        }

        try {
            writeLinesSafe(USERS_FILE, lines);
            JOptionPane.showMessageDialog(this, "Profile updated successfully!");


            txtPassword.setText("");
            txtConfirmPassword.setText("");

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Failed to update profile: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed


