     private void loadUsers() {
    DefaultTableModel model = (DefaultTableModel) tblUsers.getModel(); 
    model.setRowCount(0);

    List<String> users = FileManager.readFile(FileManager.USERS_FILE);

for (String line : users) {
    String[] parts = line.split("\\|");
    if (parts.length >= 9) {
        Object[] row = {
            parts[0],  // ID
            parts[1],  // Username
            parts[3],  // Name
            parts[4],  // Gender
            parts[5],  // Email
            parts[6],  // Phone
            parts[7],  // Date of Birth (DOB)
            parts[8]   // Type
        };
        model.addRow(row);
    }
}
}


    
private void editSelectedUser() {
        int selectedRow = tblUsers.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this,
                "Please select a user to edit",
                "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        String userID = (String) model.getValueAt(selectedRow, 0);

       
        User user = AuthManager.findUserByID(userID);

        if (user != null) {
            Window window = SwingUtilities.getWindowAncestor(this);
            EditUserDialog dialog = new EditUserDialog(window, user.findRawLine());
            dialog.setVisible(true);
            loadUsers();
        }
    }

