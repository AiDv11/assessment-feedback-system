        @Override
        protected void submitForm() {
            saveChanges();
        }
        
        private void saveChanges() {
            try {
                if (!validateInput()) return;
                
             
                User user = User.fromFileString(originalData);
                    user.updateProfile(
                    txtName.getText().trim(),
                    (String) cmbGender.getSelectedItem(),
                    txtEmail.getText().trim(),
                    txtPhone.getText().trim()
                    );
                
                if (user.updateInFile(originalData)) {
                    JOptionPane.showMessageDialog(this, "User updated successfully!", 
                        "Success", JOptionPane.INFORMATION_MESSAGE);
                    dispose();
                } else {
                    throw new Exception("Failed to update user data");
                }
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), 
                    "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        
@Override
        protected boolean validateInput() {
            String name = txtName.getText().trim();
            String email = txtEmail.getText().trim();
            String phone = txtPhone.getText().trim();
            
            if (name.isEmpty() || email.isEmpty() || phone.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all fields", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return false;
            }
            if (!UpdateUserPanel.this.isValidName(name)) {  
                setError(txtName, true);
                JOptionPane.showMessageDialog(this, "Name must contain only letters and spaces", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return false;
            }
            if (!UpdateUserPanel.this.isValidEmail(email)) {  
                setFieldError(txtEmail, true);
                JOptionPane.showMessageDialog(this, "Invalid email format", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return false;
            }
            if (!UpdateUserPanel.this.isValidPhone(phone)) {  
                setFieldError(txtPhone, true);
                JOptionPane.showMessageDialog(this, "Phone must be 10-15 digits", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return false;
            }
            return true;
        }
