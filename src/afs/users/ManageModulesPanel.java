    private void loadModules() {
    tableModel.setRowCount(0); 

    List<Module> modules = ModuleManager.getAllModules();

    for (Module module : modules) {
        Object[] row = {
            module.getModuleID(),
            module.getModuleCode(),
            module.getModuleName(),
            AssignmentManager.getLecturerNamesForModule(module.getModuleID()),
            module.getCredits(),
            module.getSemester(),
            module.getDescription()
        };
        tableModel.addRow(row);
    }
}

    

    private void applyLettersOnlyFilter(JTextField textField) {
        ((AbstractDocument) textField.getDocument()).setDocumentFilter(new DocumentFilter() {
            @Override
            public void insertString(FilterBypass fb, int offset, String string, AttributeSet attr) 
                    throws BadLocationException {
                if (string != null && string.matches("[a-zA-Z ]*")) {
                    super.insertString(fb, offset, string, attr);
                } else {
                    Toolkit.getDefaultToolkit().beep();
                }
            }

            @Override
            public void replace(FilterBypass fb, int offset, int length, String text, AttributeSet attrs) 
                    throws BadLocationException {
                if (text != null && text.matches("[a-zA-Z ]*")) {
                    super.replace(fb, offset, length, text, attrs);
                } else {
                    Toolkit.getDefaultToolkit().beep();
                }
            }
        });
    }
    

