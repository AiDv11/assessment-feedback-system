    private void addModule() {
        JTextField txtModuleName = new JTextField(20);
        JTextField txtModuleCode = new JTextField(10);
        JTextField txtCredits = new JTextField(5);
        JTextField txtSemester = new JTextField(15);
        JTextField txtDescription = new JTextField(30);
        
      
        applyLettersOnlyFilter(txtModuleName);
        applyCodeFilter(txtModuleCode);
        applyNumbersOnlyFilter(txtCredits);
        applyNumbersAndSpacesFilter(txtSemester);
        
        JPanel panel = new JPanel(new GridLayout(5, 2, 10, 10));
        panel.add(new JLabel("Module Name:"));
        panel.add(txtModuleName);
        panel.add(new JLabel("Module Code:"));
        panel.add(txtModuleCode);
        panel.add(new JLabel("Credits:"));
        panel.add(txtCredits);
        panel.add(new JLabel("Semester:"));
        panel.add(txtSemester);
        panel.add(new JLabel("Description:"));
        panel.add(txtDescription);
        
        
        while (true) {
            int result = JOptionPane.showConfirmDialog(
                this, 
                panel, 
                "Add New Module", 
                JOptionPane.OK_CANCEL_OPTION, 
                JOptionPane.PLAIN_MESSAGE
            );
            
            if (result != JOptionPane.OK_OPTION) {
                return; 
            }
            
            String name = txtModuleName.getText().trim();
            String code = txtModuleCode.getText().trim().toUpperCase();
            String creditsStr = txtCredits.getText().trim();
            String semester = txtSemester.getText().trim();
            String description = txtDescription.getText().trim();
            
           
            if (name.isEmpty() || code.isEmpty() || creditsStr.isEmpty() || semester.isEmpty()) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Please fill in all required fields!", 
                    "Validation Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
            
            if (!name.matches("[a-zA-Z ]+")) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Module Name can only contain letters and spaces!", 
                    "Validation Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
            
            if (!code.matches("[A-Z0-9-]+")) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Module Code can only contain letters, numbers, and hyphens!", 
                    "Validation Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
            
            if (!semester.matches("[0-9 ]+")) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Semester can only contain numbers and spaces!", 
                    "Validation Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
            
            int credits;
            try {
                credits = Integer.parseInt(creditsStr);
                if (credits <= 0) {
                    JOptionPane.showMessageDialog(
                        this, 
                        "Credits must be a positive number!", 
                        "Validation Error", 
                        JOptionPane.ERROR_MESSAGE
                    );
                    continue; 
                }
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Credits must be a valid number!", 
                    "Input Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
            
            
            String moduleID = ModuleManager.generateNextModuleID();
            Module newModule = new Module(moduleID, name, code, credits, description, semester);
            
            if (ModuleManager.addModule(newModule)) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Module added successfully!", 
                    "Success", 
                    JOptionPane.INFORMATION_MESSAGE
                );
                loadModules();
                return; 
            } else {
                JOptionPane.showMessageDialog(
                    this, 
                    "Failed to add module. Code may already exist.", 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE
                );
                continue; 
            }
        }
    }

